"""Rebuild every paper table from saved study reports; nothing is recomputed.

Writes docs/paper/tables.md. A report that does not exist yet is listed as
pending rather than filled with placeholder numbers.
"""

import json

from neural_cartographer.ingest.pipeline import ROOT

REPORTS = ROOT / "artifacts/reports"


def read(name):
    path = REPORTS / name
    return json.loads(path.read_text()) if path.is_file() else None


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def paired_rows(comparisons):
    rows = []
    for name, row in sorted(
        comparisons.items(), key=lambda item: item[1]["sign_flip_p"]
    ):
        ci = row["ci_fixed_repositories"]
        rows.append(
            [
                name,
                f"{row['difference']:+.3f}",
                f"{ci['lower']:+.3f} to {ci['upper']:+.3f}",
                f"{row['sign_flip_p']:.4f}",
                f"{row['holm_p']:.4f}",
                f"{row['wins']} / {row['ties']} / {row['losses']}",
            ]
        )
    return rows


PAIRED_HEADER = [
    "Primary vs",
    "Difference",
    "95% CI (projects fixed)",
    "Sign-flip p",
    "Holm p",
    "Win / tie / loss",
]


def macro_rows(macro):
    return [
        [name, f"{values['recall_at_5']:.3f}", f"{values['ndcg_at_10']:.3f}"]
        for name, values in sorted(
            macro.items(), key=lambda item: -item[1]["recall_at_5"]
        )
    ]


def slice_rows(slices):
    rows = []
    for dimension, cells in slices.items():
        for name, cell in cells.items():
            rows.append(
                [
                    dimension,
                    name,
                    cell["queries"],
                    f"{cell['first_mean']:.3f}",
                    f"{cell['second_mean']:.3f}",
                    f"{cell['wins']} / {cell['losses']}",
                ]
            )
    return rows


SLICE_HEADER = ["Slice", "Group", "Queries", "Primary", "Baseline", "Wins / losses"]


def build():
    sections = ["# Paper tables", "Generated by `scripts/build_tables.py` from saved reports."]
    v1 = read("v1-paired-analysis.json")
    sections.append("## Table 1. v1 pilot: paired comparisons, Recall@5")
    if v1:
        sections.append(table(PAIRED_HEADER, paired_rows(v1["comparisons"]["recall_at_5"])))
        sections.append("## Table 2. v1 pilot: error slices, Recall@5 (fusion vs co-change)")
        sections.append(table(SLICE_HEADER, slice_rows(v1["slices"]["recall_at_5"])))
    else:
        sections.append("Pending: `v1-paired-analysis.json` does not exist yet.")
    development = read("v2-development.json")
    sections.append("## Table 3. v2 validation selection (macro over validation projects)")
    if development:
        choice = development["choice"]
        sections.append(
            f"Primary: `{choice['primary']}`. Baseline: `{choice['baseline']}`. "
            f"Hybrid: `{choice['hybrid']['gnn']}` at weight {choice['hybrid']['weight']}."
        )
        sections.append(table(["System", "Recall@5", "NDCG@10"], macro_rows(development["macro"])))
    else:
        sections.append("Pending: `v2-development.json` does not exist yet.")
    final = read("v2-final.json")
    sections.append("## Table 4. v2 fresh test (macro over five projects)")
    if final:
        gate = final["pre_registered_gate"]
        sections.append(
            f"Pre-registered gate met: **{gate['met']}** "
            f"(difference {gate['difference']:+.3f}, sign-flip p = {gate['sign_flip_p']:.4f})."
        )
        sections.append(table(["System", "Recall@5", "NDCG@10"], macro_rows(final["macro"])))
        sections.append("## Table 5. v2 fresh test: paired comparisons, Recall@5")
        sections.append(table(PAIRED_HEADER, paired_rows(final["comparisons"]["recall_at_5"])))
        sections.append("## Table 6. v2 fresh test: error slices, Recall@5")
        sections.append(table(SLICE_HEADER, slice_rows(final["slices"]["recall_at_5"])))
    else:
        sections.append("Pending: `v2-final.json` does not exist yet.")
    destination = ROOT / "docs/paper/tables.md"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n\n".join(sections) + "\n", encoding="utf-8")
    return destination


if __name__ == "__main__":
    print("Wrote", build())
